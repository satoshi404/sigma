int main()
{
  // Toolchain
  {
    Array<Target> targets;

    if ( !Build::init_boot() )            return -1;
    if ( !Build::init_parser( targets ) ) return -1;
    if ( !Build::init_build( targets ) )  return -1;
  }

  return 0;
}

